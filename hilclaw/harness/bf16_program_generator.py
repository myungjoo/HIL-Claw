"""C sources of the bf16 harness programs of four kinds, generated from the contract table (ADR-0193 decision 6).

``ARCHITECTURE/decisions/ADR-0193-od32-generalization-design.md`` decision 6
makes the verification program of ADR-0163 and the timing program of ADR-0181
decision 2 of each kind of :data:`GENERATED_KINDS` the output of a pure
function of a contract-table entry. :func:`verification_source` and
:func:`timing_source` return the text of such a program; it includes the
shared header (``bf16_verification.h`` or ``bf16_timing.h``) with quotes, as
the handwritten programs of ``rope`` and ``sdpa_kv_cache`` do, and has the
same command line, argument checks, draws, check values, output fill, report,
calls and exit statuses as the handwritten program of the same kind and form
(for the verification programs, as it had before it was removed).
:func:`verification_name` and :func:`timing_name` give the file name the
program has next to those headers.

What is read, all from the bf16 entry of the kind in
:data:`hilclaw.contract_table.TABLE`:

* ``PROTOTYPE``: the entry point, its parameters in order and their C types;
* the parameters of ``task_contract``: the dimensions and their order on the
  command line;
* the operands of ``task_contract``, called with a distinct prime for each
  dimension, each operand's shape entry read back as the dimension whose prime
  it equals: the name, role and shape of each operand;
* ``DRAW_BITS``: the ``bits`` of each input operand, in the order of the
  operands;
* for each ``float`` parameter ``p`` of the prototype, the constant
  ``P_BITS`` (``p`` in upper case): the binary32 bit pattern the program
  passes for it.

One difference of the kinds is not in the table and is kept here: whether the
size check also refuses two input arrays whose bytes together do not fit in
``size_t`` (every kind but ``gemm``).

What the module does not do: it reads and writes no file, starts no process,
builds nothing and keeps nothing between calls. It imports no NumPy.
"""

import inspect
import re
import types

from hilclaw import contract_table

__all__ = [
    "GENERATED_KINDS",
    "timing_name",
    "timing_source",
    "verification_name",
    "verification_source",
]

GENERATED_KINDS = ("gemm", "rmsnorm", "elementwise_add", "swiglu")

_INPUTS_FIT_TOGETHER = {
    "gemm": False,
    "rmsnorm": True,
    "elementwise_add": True,
    "swiglu": True,
}

_PRIMES = (2, 3, 5, 7, 11, 13, 17, 19)
_OR = " ||\n        "
_FLOAT_SIZE = (
    "typedef char float_has_32_bits[sizeof(float) == sizeof(uint32_t) ? 1 : -1];"
)
_TOO_LARGE = "an array of these dimensions does not fit in size_t"
_NO_MEMORY = "cannot allocate the operands"


def verification_name(kind):
    """Return the file name of the verification program of ``kind``, e.g. ``bf16_verification_swiglu.c``.

    Raises :class:`ValueError` with the attribute ``parameter`` set to
    ``"kind"`` for a ``kind`` that is not exactly a ``str`` of
    :data:`GENERATED_KINDS`.
    """
    return f"bf16_verification_{_kind(kind)}.c"


def timing_name(kind):
    """Return the file name of the timing program of ``kind``, e.g. ``bf16_timing_swiglu.c``.

    Raises as :func:`verification_name` raises.
    """
    return f"bf16_timing_{_kind(kind)}.c"


def verification_source(kind):
    """Return the C source text of the verification program of ``kind`` (ADR-0163).

    The command line is ``<dimensions...> <draws> <seed>``, the dimensions in
    the order of the kind's ``task_contract`` parameters. Raises as
    :func:`verification_name` raises.
    """
    plan = _plan(_kind(kind))
    usage = " ".join(f"<{name}>" for name in (*plan.dims, "draws", "seed"))
    count = len(plan.dims)
    first, second = plan.inputs
    lines = [
        "/*",
        f" * Verification program of a bf16 verification run of {kind} (ADR-0163),",
        " * generated by hilclaw.harness.bf16_program_generator from the contract",
        " * table (ADR-0193 decision 6). Command line:",
        " *",
        f" *     {usage}",
        " */",
        "#define _POSIX_C_SOURCE 200809L",
        f'#define PROGRAM "bf16_verification_{kind}"',
        "",
        '#include "bf16_verification.h"',
        *plan.preamble,
        "",
        plan.prototype,
        "",
        "int main(int argc, char **argv)",
        "{",
        *plan.declarations,
        "    uint64_t draws, seed, d, base;",
        "    uint32_t check;",
        "    int report;",
        "",
        f"    if (argc != {count + 3})",
        f'        return fail(STATUS_COMMAND_LINE, "usage", "{usage}");',
        *plan.parsed,
        f'    draws = digits("draws", argv[{count + 1}], 1, UINT64_MAX);',
        f'    seed = digits("seed", argv[{count + 2}], 0, UINT64_MAX);',
        *plan.scalars,
        "",
        *plan.allocation,
        "",
        "    report = report_open();",
        "    for (d = 0; d < draws; d++) {",
        "        base = draw_base(seed, d);",
        *(f"    {line}" for line in plan.draws),
        f"        check = check_value({first.name}, {first.bytes}, {second.name}, {second.bytes});",
        "        emit(report, &check, sizeof check);",
        f"        fill_output({plan.output.name}, {plan.output.count});",
        f"        {plan.call};",
        f"        emit(report, {plan.output.name}, {plan.output.bytes});",
        "    }",
        '    emit(report, "end\\n", 4);',
        *plan.frees,
        "    return 0;",
        "}",
    ]
    return "\n".join(lines) + "\n"


def timing_source(kind):
    """Return the C source text of the timing program of ``kind`` (ADR-0181 decision 2).

    The command line is ``<dimensions...> <n_min> <n_max> <cv_max>
    <sample_form> <seed>``; the inputs are draw 0 of the verification program
    with the timing seed, and the output is not initialised. Raises as
    :func:`verification_name` raises.
    """
    plan = _plan(_kind(kind))
    dims = " ".join(f"<{name}>" for name in plan.dims)
    count = len(plan.dims)
    lines = [
        "/*",
        f" * Timing program of a bf16 timing run of {kind} (ADR-0181 decision 2),",
        " * generated by hilclaw.harness.bf16_program_generator from the contract",
        " * table (ADR-0193 decision 6). Command line:",
        " *",
        f" *     {dims} <n_min> <n_max> <cv_max> <sample_form> <seed>",
        " */",
        "#define _POSIX_C_SOURCE 200809L",
        f'#define PROGRAM "bf16_timing_{kind}"',
        "",
        '#include "bf16_timing.h"',
        *plan.preamble,
        "",
        plan.prototype,
        "",
        f"typedef void kernel_function({', '.join(plan.types)});",
        "",
        f"static kernel_function *volatile kernel = {plan.symbol};",
        "",
        "int main(int argc, char **argv)",
        "{",
        *plan.declarations,
        "    uint64_t base;",
        "    kernel_function *call;",
        "    struct timing t;",
        "",
        f"    if (argc != {count + 6})",
        f'        return fail(STATUS_COMMAND_LINE, "usage", "{dims} " TIMING_USAGE);',
        *plan.parsed,
        f"    timing_arguments(&t, argv + {count + 1});",
        *plan.scalars,
        "",
        *plan.allocation,
        "    base = draw_base(t.seed, 0);",
        *plan.draws,
        "",
        "    call = kernel;",
        "    for (timing_open(&t); timing_begin(&t); timing_end(&t))",
        f"        call{plan.call.removeprefix(plan.symbol)};",
        "    timing_close(&t);",
        *plan.frees,
        "    return 0;",
        "}",
    ]
    return "\n".join(lines) + "\n"


class _Operand:
    def __init__(self, name, shape):
        self.name = name
        self.bytes = f"{name}_bytes"
        self.count = " * ".join(shape)
        self.rows, self.columns = shape if len(shape) == 2 else ("1", shape[0])


def _plan(kind):
    contract = next(
        found.contract
        for key, found in contract_table.TABLE.items()
        if key[:2] == (kind, "bf16")
    )
    plan = types.SimpleNamespace()
    plan.dims = tuple(inspect.signature(contract.task_contract).parameters)
    probes = dict(zip(plan.dims, _PRIMES, strict=False))
    named = {value: name for name, value in probes.items()}
    roles = {"input": [], "output": []}
    for operand in contract.task_contract(**probes)["operands"]:
        shape = [named[value] for value in operand["shape"]]
        roles[operand["role"]].append(_Operand(operand["name"], shape))
    first, second = plan.inputs = roles["input"]
    (plan.output,) = roles["output"]
    arrays = (first, second, plan.output)

    plan.prototype = contract.PROTOTYPE
    match = re.fullmatch(r"void (\w+)\((.*)\);", contract.PROTOTYPE)
    plan.symbol = match.group(1)
    parameters = [
        re.fullmatch(r"(.*?)\s*(\w+)", text).groups()
        for text in match.group(2).split(", ")
    ]
    plan.types = [ctype for ctype, _ in parameters]
    plan.call = f"{plan.symbol}({', '.join(name for _, name in parameters)})"
    scalars = [name for ctype, name in parameters if ctype == "float"]

    plan.preamble = []
    if scalars:
        plan.preamble = ["", "#include <string.h>", "", _FLOAT_SIZE]
    constants = [
        f"    const uint32_t {name}_bits = "
        f"UINT32_C(0x{getattr(contract, f'{name.upper()}_BITS'):08X});"
        for name in scalars
    ]
    plan.declarations = [
        *constants,
        f"    size_t {', '.join(plan.dims)};",
        f"    size_t {', '.join(a.bytes for a in arrays)};",
        f"    uint16_t {', '.join(f'*{a.name}' for a in arrays)};",
        *(f"    float {name};" for name in scalars),
    ]
    plan.scalars = [
        f"    memcpy(&{name}, &{name}_bits, sizeof {name});" for name in scalars
    ]
    plan.parsed = [
        f'    {name} = (size_t)digits("{name}", argv[{index}], 1, SIZE_MAX);'
        for index, name in enumerate(plan.dims, start=1)
    ]

    checks = [
        f"!byte_size({a.rows}, {a.columns}, sizeof(uint16_t), &{a.bytes})"
        for a in arrays
    ]
    if _INPUTS_FIT_TOGETHER[kind]:
        checks.append(f"{first.bytes} > SIZE_MAX - {second.bytes}")
    plan.allocation = [
        f"    if ({_OR.join(checks)})",
        f'        return fail(STATUS_MEMORY, "sizes", "{_TOO_LARGE}");',
        *(f"    {a.name} = malloc({a.bytes});" for a in arrays),
        f"    if ({' || '.join(f'{a.name} == NULL' for a in arrays)})",
        f'        return fail(STATUS_MEMORY, "malloc", "{_NO_MEMORY}");',
    ]

    first_bits, second_bits = contract.DRAW_BITS
    offset = f"(uint64_t)({first.count})"
    plan.draws = [
        f"    draw_patterns({first.name}, {first.count}, base, 0, {first_bits});",
        f"    draw_patterns({second.name}, {second.count}, base, {offset}, {second_bits});",
    ]
    plan.frees = [f"    free({a.name});" for a in reversed(arrays)]
    return plan


def _kind(kind):
    if type(kind) is not str or kind not in GENERATED_KINDS:
        error = ValueError(
            f"kind must be one of {', '.join(map(repr, GENERATED_KINDS))}, not {kind!r}"
        )
        error.parameter = "kind"
        raise error
    return kind
